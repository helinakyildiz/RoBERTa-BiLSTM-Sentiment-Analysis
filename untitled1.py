def plot_history(history, name):
    ep = range(1, len(history["train_loss"])+1)
    fig, axes = plt.subplots(1, 2, figsize=(13, 4))

    # Kayıp eğrisi
    axes[0].plot(ep, history["train_loss"], "b-o", label="Eğitim")
    axes[0].plot(ep, history["val_loss"],   "r-o", label="Doğrulama")
    axes[0].set_title(f"{name} — Kayıp"); axes[0].set_xlabel("Epoch")
    axes[0].set_ylabel("Kayıp"); axes[0].legend(); axes[0].grid(alpha=0.3)

    # Doğruluk & F1
    axes[1].plot(ep, [a*100 for a in history["train_acc"]], "b-o", label="Eğitim Acc")
    axes[1].plot(ep, [a*100 for a in history["val_acc"]],   "r-o", label="Doğrulama Acc")
    axes[1].plot(ep, [f*100 for f in history["val_f1"]],    "g--s", label="Doğrulama F1w")
    axes[1].set_title(f"{name} — Doğruluk & F1"); axes[1].set_xlabel("Epoch")
    axes[1].set_ylim(0, 100); axes[1].legend(); axes[1].grid(alpha=0.3)

    plt.suptitle(f"RoBERTa-BiLSTM — {name}", fontsize=13, fontweight="bold")
    plt.tight_layout()
    plt.savefig(f"history_{name}.png", dpi=130); plt.show()


def plot_confusion(labels, preds, class_names, name):
    cm = confusion_matrix(labels, preds)
    fig, ax = plt.subplots(figsize=(len(class_names)*2, len(class_names)*2))
