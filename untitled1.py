def augment_class(df, label, target_count, aug):
    """Belirtilen sınıfı hedef sayıya kadar artır."""
    subset = df[df["label"] == label].copy()
    current = len(subset)
    needed  = target_count - current
    if needed <= 0:
        return subset

    texts = subset["text"].tolist()
    augmented_texts = []

    print(f"'{label}' için {needed} örnek üretiliyor...")
    while len(augmented_texts) < needed:
        batch = texts[:min(100, needed - len(augmented_texts))]
        try:
            result = aug.augment(batch)
            augmented_texts.extend(result)
        except:
            augmented_texts.extend(batch)  # hata olursa orijinali ekle

    aug_df = pd.DataFrame({
        "text": augmented_texts[:needed],
        "label": label,
        "label_enc": df[df["label"] == label]["label_enc"].iloc[0]
    })
    return pd.concat([subset, aug_df], ignore_index=True)

