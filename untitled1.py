"""Makalenin önerdiği hibrit model tanımlanır. RoBERTa encoder (12 katman, 768 gizli birim) → Dropout (0.1) → BiLSTM (h=256, çıktı=512) → Dense katman → Softmax."""

# ============================================================
# HÜCRE: RoBERTa-BiLSTM Model  (Makale Bölüm IV, Şekil 1)
# ============================================================
# Mimari akışı (Algoritma 1):
#   Adım 16: RoBERTa Tokenization
#   Adım 17: RoBERTa Encoder (12 katman, 768 gizli birim)
#   Adım 18: Dropout (d=0.1)
#   Adım 19: BiLSTM (h=256, bidirectional → çıktı=512)
#   Adım 20: Flatten (ortalama havuzlama)
#   Adım 21: Dense katman 1
#   Adım 22: Dense katman 2 + Softmax

HIDDEN_UNITS = 256    # h ∈ {128,256,512} → makale en iyi: 256
DROPOUT      = 0.1    # d = 0.1
EPOCHS       = 5      # epoch = 5
LEARNING_RATE= 1e-5   # l = 0.00001 (makale en iyi)
WEIGHT_DECAY = 1e-2


class RoBERTaBiLSTM(nn.Module):


    def __init__(self, num_classes, hidden_units=HIDDEN_UNITS, dropout=DROPOUT):
        super().__init__()

        # Adım 17: RoBERTa Encoder
        self.roberta = RobertaModel.from_pretrained("roberta-base")
        roberta_dim  = self.roberta.config.hidden_size  # 768

        # Adım 18: Dropout
        self.dropout = nn.Dropout(dropout)

        # Adım 19: BiLSTM
        # "hidden units (h) will be doubled (2×h) for BiLSTM"
        self.bilstm = nn.LSTM(
            input_size  = roberta_dim,
            hidden_size = hidden_units,
            num_layers  = 1,
            batch_first = True,
            bidirectional=True,    # ileri (→) + geri (←)
        )
        bilstm_out = hidden_units * 2   # 256×2 = 512

        # Adım 21: Dense katman 1
        self.fc1   = nn.Linear(bilstm_out, 128)
        self.relu  = nn.ReLU()
        self.drop2 = nn.Dropout(dropout)

        # Adım 22: Dense katman 2 / Sınıflandırma
        # Softmax → CrossEntropyLoss içinde uygulanır
        self.fc2 = nn.Linear(128, num_classes)

    def forward(self, input_ids, attention_mask):
        # 1) RoBERTa: (B, L) → (B, L, 768)
        rob_out = self.roberta(
            input_ids=input_ids,
            attention_mask=attention_mask
        )
        seq_out = rob_out.last_hidden_state   # (B, L, 768)

        # 2) Dropout
        seq_out = self.dropout(seq_out)       # (B, L, 768)

        # 3) BiLSTM: (B, L, 768) → (B, L, 512)
        lstm_out, _ = self.bilstm(seq_out)

        # 4) Flatten: ortalama havuzlama (B, L, 512) → (B, 512)
        pooled = lstm_out.mean(dim=1)

        # 5) Dense + ReLU
        out = self.relu(self.fc1(pooled))
        out = self.drop2(out)

        # 6) Sınıflandırma logits (B, num_classes)
        return self.fc2(out)


