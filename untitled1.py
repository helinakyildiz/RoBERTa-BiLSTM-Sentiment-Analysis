from transformers import get_linear_schedule_with_warmup
import time

def train_one_epoch(model, loader, optimizer, scheduler,
                    criterion, scaler):

    model.train()
    total_loss = correct = total = 0

    for batch in loader:
        inp  = batch["input_ids"].to(device)
        mask = batch["attention_mask"].to(device)
        lbl  = batch["label"].to(device)

        optimizer.zero_grad()
        with torch.cuda.amp.autocast():
            logits = model(inp, mask)
            loss   = criterion(logits, lbl)  # Denklem 9

        scaler.scale(loss).backward()
        scaler.unscale_(optimizer)
        nn.utils.clip_grad_norm_(model.parameters(), 1.0)
        scaler.step(optimizer)
        scaler.update()
        scheduler.step()

        total_loss += loss.item() * lbl.size(0)
        correct    += (logits.argmax(1) == lbl).sum().item()
        total      += lbl.size(0)

    return total_loss/total, correct/total


@torch.no_grad()
def evaluate(model, loader, criterion):

    model.eval()
    total_loss = correct = total = 0
    all_preds, all_labels = [], []

    for batch in loader:
        inp  = batch["input_ids"].to(device)
        mask = batch["attention_mask"].to(device)
        lbl  = batch["label"].to(device)

        with torch.cuda.amp.autocast():
            logits = model(inp, mask)
            loss   = criterion(logits, lbl)

        total_loss += loss.item() * lbl.size(0)
        preds       = logits.argmax(1)
        correct    += (preds == lbl).sum().item()
        total      += lbl.size(0)
        all_preds.extend(preds.cpu().numpy())
        all_labels.extend(lbl.cpu().numpy())

    acc  = correct / total
    f1w  = f1_score(all_labels, all_preds, average="weighted", zero_division=0)
    pw   = precision_score(all_labels, all_preds, average="weighted", zero_division=0)
    rw   = recall_score(all_labels, all_preds, average="weighted", zero_division=0)
    return total_loss/total, acc, f1w, pw, rw, all_preds, all_labels


def full_train(model, train_loader, val_loader,
               num_epochs, dataset_name):
    """
    5 epoch AdamW + linear warmup schedule.
    Her epoch sonunda en iyi model (val F1'e göre) kaydedilir.
    """
    criterion = nn.CrossEntropyLoss()
    optimizer = AdamW(model.parameters(),
                      lr=LEARNING_RATE, weight_decay=WEIGHT_DECAY)
    total_steps  = len(train_loader) * num_epochs
    warmup_steps = int(0.1 * total_steps)
    scheduler = get_linear_schedule_with_warmup(
        optimizer, warmup_steps, total_steps)
    scaler = torch.cuda.amp.GradScaler()

    history   = {k: [] for k in
                 ["train_loss","val_loss","train_acc","val_acc",
                  "val_f1","val_pw","val_rw"]}
    best_f1   = 0.0
    save_path = f"best_{dataset_name}.pt"

    print(f"\n{'='*60}")
    print(f"  {dataset_name} Eğitimi")
    print(f"  Epochs:{num_epochs}  Batch:{BATCH_SIZE}  "
          f"LR:{LEARNING_RATE}  h:{HIDDEN_UNITS}")
    print(f"{'='*60}")

    for ep in range(1, num_epochs+1):
        t0 = time.time()
        tr_loss, tr_acc = train_one_epoch(
            model, train_loader, optimizer,
            scheduler, criterion, scaler)
        vl_loss, vl_acc, vl_f1, vl_pw, vl_rw, _, _ = evaluate(
            model, val_loader, criterion)
        elapsed = time.time() - t0

        for k, v in zip(history,
                        [tr_loss,vl_loss,tr_acc,vl_acc,vl_f1,vl_pw,vl_rw]):
            history[k].append(v)

        print(f"Epoch {ep}/{num_epochs} [{elapsed:.0f}s] "
              f"TrLoss:{tr_loss:.4f} TrAcc:{tr_acc*100:.2f}% | "
              f"VlLoss:{vl_loss:.4f} VlAcc:{vl_acc*100:.2f}% "
              f"F1w:{vl_f1*100:.2f}%")

        if vl_f1 > best_f1:
            best_f1 = vl_f1
            torch.save(model.state_dict(), save_path)
            print(f"  ✓ En iyi model kaydedildi (Val F1:{best_f1*100:.2f}%)")

    return history, save_path


