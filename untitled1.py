def predict_single(text, model_path, num_classes, class_names_display):
    model = RoBERTaBiLSTM(num_classes=num_classes).to(device)
    model.load_state_dict(torch.load(model_path, map_location=device))
    model.eval()

    cleaned = preprocess(text)

    enc = tokenizer(
        cleaned,
        max_length=MAX_LEN,
        padding="max_length",
        truncation=True,
        return_tensors="pt",
    )
    inp  = enc["input_ids"].to(device)
    mask = enc["attention_mask"].to(device)

    with torch.no_grad():
        with torch.cuda.amp.autocast():
            logits = model(inp, mask)
        probs    = torch.softmax(logits, dim=1).cpu().numpy()[0]
        pred_idx = probs.argmax()

    pred_label = class_names_display[pred_idx]

    print(f"  Ham metin    : {text}")
    print(f"  Temizlenmiş  : {cleaned if cleaned else '(boş)'}")
    print(f"  Tahmin       : ► {pred_label} ◄")
    print(f"  Olasılıklar  :")
    for i, (cn, p) in enumerate(zip(class_names_display, probs)):
        bar    = "█" * int(p * 30)
        marker = " ◀" if i == pred_idx else ""
        print(f"    {cn:<14}: {p*100:5.1f}%  {bar}{marker}")
    print()

    del model
    torch.cuda.empty_cache()
    return pred_label, probs


