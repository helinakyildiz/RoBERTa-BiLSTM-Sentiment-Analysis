class SentimentDataset(Dataset):
    """
    Makale Adım 16:
    Her token için → Input ID + Attention Mask atanır
    """
    def __init__(self, texts, labels, tokenizer, max_len):
        self.texts     = texts
        self.labels    = labels
        self.tokenizer = tokenizer
        self.max_len   = max_len

    def __len__(self):
        return len(self.texts)

    def __getitem__(self, idx):
        enc = self.tokenizer(
            str(self.texts[idx]),
            max_length=self.max_len,
            padding="max_length",
            truncation=True,
            return_tensors="pt",
        )
        return {
            "input_ids":      enc["input_ids"].squeeze(0),
            "attention_mask": enc["attention_mask"].squeeze(0),
            "label": torch.tensor(self.labels[idx], dtype=torch.long),
        }


def make_loaders(train_df, val_df, test_df,
                 text_col="text", label_col="label_enc"):
    def mk(df, shuffle):
        return DataLoader(
            SentimentDataset(
                df[text_col].tolist(),
                df[label_col].tolist(),
                tokenizer, MAX_LEN
            ),
            batch_size=BATCH_SIZE,
            shuffle=shuffle,
            num_workers=2,
            pin_memory=True,
        )
    return mk(train_df, True), mk(val_df, False), mk(test_df, False)


